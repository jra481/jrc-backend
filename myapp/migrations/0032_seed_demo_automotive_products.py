def seed_demo_automotive_products(apps, schema_editor):
    Product = apps.get_model("myapp", "Product")
    ProductVariant = apps.get_model("myapp", "ProductVariant")

    for index, (
        kind,
        name,
        description,
        vehicle,
        manufacturer,
        key_features,
        price_label,
        price,
        stock,
    ) in enumerate(DEMO_PRODUCTS, start=1):
        product, _ = Product.objects.get_or_create(
            name=name,
            defaults={
                "description": description,
                "vehicle": vehicle,
                "manufacturer": manufacturer,
                "key_features": key_features,
                "shipping_fee": 0,
                "estimated_delivery_time": "2-5 working days",
                "seller_name": "Jamal Rafeeq Demo Catalog",
                "warranty_info": "Demo listing - confirm warranty before sale.",
                "is_active": True,
            },
        )

        variant = ProductVariant.objects.filter(product=product, color__isnull=True).first()
        if variant is None:
            variant = ProductVariant.objects.create(
                product=product,
                sku=f"DEMO-{kind.upper()}-{index:02d}",
                price_type="single",
                price=price,
                stock=stock,
            )
        elif not variant.sku:
            variant.sku = f"DEMO-{kind.upper()}-{index:02d}"
            variant.price = price
            variant.stock = stock
            variant.price_type = "single"
            variant.save(update_fields=["sku", "price", "stock", "price_type"])


